-- 1. 기존 구버전 orders 테이블이 있다면 완전히 삭제하고 새로 생성
drop table if exists public.orders cascade;

-- 2. 요청하신 최신 열 구성으로 orders 테이블 생성
create table public.orders (
  id bigint generated by default as identity primary key,   -- 고유 주문 번호 (#1, #2...)
  created_at timestamp with time zone default timezone('utc'::text, now()) not null, -- 주문 일시
  customer_name text not null,                              -- 주문자 이름 (필수)
  phone text,                                               -- 전화번호
  drink text not null,                                      -- 음료 이름 (예: '카페라떼', '딸기 스무디')
  drink_price integer not null check (drink_price >= 0),    -- 음료 기본 가격
  size text,                                                -- 사이즈 ('S', 'M', 'L' / 딸기 스무디는 null)
  options text[] default '{}'::text[],                      -- 추가 옵션 배열 (예: ARRAY['샷 추가', '크림 추가'])
  quantity integer default 1 not null check (quantity >= 1 and quantity <= 10), -- 수량 (1~10)
  request text,                                             -- 요청사항
  total_price integer not null check (total_price >= 0)      -- 총 결제/예상 금액
);

-- 테이블 설명 코멘트 추가
comment on table public.orders is '바이브 카페 주문서 내역 테이블';

-- 3. Row Level Security(RLS) 활성화
alter table public.orders enable row level security;

-- 4. 웹 페이지(익명 사용자 anon) 접근 권한 정책 설정
-- [INSERT 정책] 웹 페이지 방문자가 주문서를 저장(추가)할 수 있도록 허용
create policy "누구나 주문 추가 가능"
  on public.orders
  for insert
  to anon, authenticated
  with check (true);

-- [SELECT 정책] 주문 내역 목록을 조회할 수 있도록 허용
create policy "누구나 주문 내역 조회 가능"
  on public.orders
  for select
  to anon, authenticated
  using (true);

-- [DELETE 정책] 주문 취소 및 내역 모두 지우기를 수행할 수 있도록 허용
create policy "누구나 주문 삭제/취소 가능"
  on public.orders
  for delete
  to anon, authenticated
  using (true);

-- ========================================================
-- 5. 테스트 주문 데이터 삽입 (확인용)
-- ========================================================
